// Usage: bun scripts/gen-wordlist.ts <path/to/wordlist.txt>
// Emits src/core/slip39/wordlist.ts from the SLIP-39 word list.
import { readFileSync, writeFileSync } from "node:fs";

const path = process.argv[2];
if (!path) {
  console.error("usage: bun scripts/gen-wordlist.ts <wordlist.txt>");
  process.exit(1);
}
const words = readFileSync(path, "utf8")
  .split(/\r?\n/)
  .map((w) => w.trim())
  .filter((w) => w.length > 0);
if (words.length !== 1024) throw new Error(`expected 1024 words, got ${words.length}`);

const out =
  `// Generated by scripts/gen-wordlist.ts from trezor/python-shamir-mnemonic (MIT). See third_party/NOTICE.\n` +
  `// Do not edit by hand.\n` +
  `export const WORDLIST: readonly string[] = [\n` +
  words.map((w) => `  ${JSON.stringify(w)},\n`).join("") +
  `];\n`;
writeFileSync(new URL("../src/core/slip39/wordlist.ts", import.meta.url), out);
